-- 7. Stored procedure for atomic orders with stock validation
CREATE OR REPLACE FUNCTION public.place_order_atomic(
    p_customer_name TEXT,
    p_user_id BIGINT,
    p_items JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
    v_order_id BIGINT;
    v_total_price NUMERIC(10, 2) := 0;
    v_item JSONB;
    v_med_id BIGINT;
    v_qty INT;
    v_price NUMERIC(10, 2);
    v_stock INT;
    v_med_name TEXT;
BEGIN
    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Order must contain at least one item';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM jsonb_array_elements(p_items) AS entries(entry)
        WHERE entry->>'medicine_id' IS NULL
            OR entry->>'quantity' IS NULL
            OR (entry->>'quantity')::INT <= 0
    ) THEN
        RAISE EXCEPTION 'Each order item must include a medicine ID and a positive quantity';
    END IF;

    -- Lock rows in a stable order and aggregate duplicate medicine lines before checking stock.
    PERFORM m.id
    FROM public.medicines m
    JOIN (
        SELECT (entry->>'medicine_id')::BIGINT AS medicine_id
        FROM jsonb_array_elements(p_items) AS entries(entry)
        GROUP BY 1
    ) requested ON requested.medicine_id = m.id
    ORDER BY m.id
    FOR UPDATE OF m;

    FOR v_item IN
        SELECT jsonb_build_object(
            'medicine_id', (entry->>'medicine_id')::BIGINT,
            'quantity', SUM((entry->>'quantity')::INT)
        )
        FROM jsonb_array_elements(p_items) AS entries(entry)
        GROUP BY (entry->>'medicine_id')::BIGINT
        ORDER BY (entry->>'medicine_id')::BIGINT
    LOOP
        v_med_id := (v_item->>'medicine_id')::BIGINT;
        v_qty := (v_item->>'quantity')::INT;

        IF v_med_id IS NULL OR v_qty IS NULL OR v_qty <= 0 THEN
            RAISE EXCEPTION 'Each order item must include a medicine ID and a positive quantity';
        END IF;

        SELECT name, price, stock INTO v_med_name, v_price, v_stock
        FROM public.medicines
        WHERE id = v_med_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Medicine with ID % not found', v_med_id;
        END IF;

        IF v_stock < v_qty THEN
            RAISE EXCEPTION 'Medicine % is out of stock (Available: %, Requested: %)', v_med_name, v_stock, v_qty;
        END IF;

        v_total_price := v_total_price + (v_price * v_qty);
    END LOOP;

    -- 2. Insert into orders
    INSERT INTO public.orders (user_id, customer_name, total_price, status)
    VALUES (p_user_id, p_customer_name, v_total_price, 'Processing')
    RETURNING id INTO v_order_id;

    -- 3. Insert order items & deduct stock
    FOR v_item IN
        SELECT jsonb_build_object(
            'medicine_id', (entry->>'medicine_id')::BIGINT,
            'quantity', SUM((entry->>'quantity')::INT)
        )
        FROM jsonb_array_elements(p_items) AS entries(entry)
        GROUP BY (entry->>'medicine_id')::BIGINT
        ORDER BY (entry->>'medicine_id')::BIGINT
    LOOP
        v_med_id := (v_item->>'medicine_id')::BIGINT;
        v_qty := (v_item->>'quantity')::INT;

        INSERT INTO public.order_items (order_id, medicine_id, quantity)
        VALUES (v_order_id, v_med_id, v_qty);

        UPDATE public.medicines
        SET stock = stock - v_qty, updated_at = NOW()
        WHERE id = v_med_id;
    END LOOP;

    RETURN jsonb_build_object(
        'message', 'Order Placed Successfully',
        'order_id', v_order_id,
        'total_price', v_total_price
    );
END;
$$;
